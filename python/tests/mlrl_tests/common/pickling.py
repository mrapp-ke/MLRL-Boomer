import pickle
from typing import Any

import numpy as np
from mlrl.common.cython.output_space_info import OutputSpaceInfo
from mlrl.common.cython.probability_calibration import (
    JointProbabilityCalibrationModel,
    MarginalProbabilityCalibrationModel,
)
from mlrl.common.cython.rule_model import RuleModel
from scipy.sparse import issparse
from sklearn.datasets import make_multilabel_classification, make_regression

INCREMENTAL_STEP_SIZE = 3


def create_classification_dataset(num_examples: int = 150, num_features: int = 8, num_labels: int = 5):
    """
    Creates a synthetic multi-label classification dataset with numerical, ordinal and nominal features.

    :return: A tuple that contains the feature matrix, the label matrix, and the indices of ordinal and nominal features
    """
    x, y = make_multilabel_classification(
        n_samples=num_examples, n_features=num_features, n_classes=num_labels, random_state=42
    )
    x = x.astype(np.float32)
    # The features generated by scikit-learn are counts, i.e., they can be treated as ordinal or nominal features
    ordinal_feature_indices = [0, 1]
    nominal_feature_indices = [2, 3]
    x[:, 4:] += np.random.default_rng(42).random((num_examples, num_features - 4), dtype=np.float32)
    return x, y, ordinal_feature_indices, nominal_feature_indices


def create_regression_dataset(num_examples: int = 150, num_features: int = 8, num_outputs: int = 3):
    """
    Creates a synthetic multi-output regression dataset.

    :return: A tuple that contains the feature matrix and the regression matrix
    """
    x, y = make_regression(n_samples=num_examples, n_features=num_features, n_targets=num_outputs, random_state=42)
    return x.astype(np.float32), y


def _to_dense(array: Any) -> np.ndarray:
    return array.toarray() if issparse(array) else np.asarray(array)


def _assert_identical(expected: Any, actual: Any, description: str):
    expected = _to_dense(expected)
    actual = _to_dense(actual)
    assert expected.dtype == actual.dtype, f'{description}: The data types differ'
    np.testing.assert_array_equal(actual, expected, err_msg=description)


def _assert_identical_incremental_predictions(original, loaded, method_name: str, x):
    original_predictor = getattr(original, method_name)(x)
    loaded_predictor = getattr(loaded, method_name)(x)
    step = 0

    while original_predictor.has_next():
        assert loaded_predictor.has_next(), f'{method_name}: The loaded learner provides fewer incremental predictions'
        _assert_identical(
            original_predictor.apply_next(INCREMENTAL_STEP_SIZE),
            loaded_predictor.apply_next(INCREMENTAL_STEP_SIZE),
            f'{method_name} (step {step})',
        )
        step += 1

    assert not loaded_predictor.has_next(), f'{method_name}: The loaded learner provides more incremental predictions'


def _supports(learner, method_name: str, x) -> bool:
    if not hasattr(learner, method_name):
        return False

    try:
        getattr(learner, method_name)(x)
        return True
    except (RuntimeError, ValueError, NotImplementedError):
        # Not all prediction types are supported by all configurations
        return False


def assert_identical_after_pickling(learner, x):
    """
    Pickles and unpickles a fitted learner and asserts that the native objects are restored with the same types and that
    all supported types of predictions, including incremental predictions, are identical.

    :param learner: The fitted learner
    :param x:       The feature matrix that should be used for obtaining predictions
    :return:        The unpickled learner
    """
    data = pickle.dumps(learner)
    loaded = pickle.loads(data)
    assert_identical_learners(learner, loaded, x)
    # Pickling the unpickled learner again must result in an equivalent learner
    _assert_identical(learner.predict(x), pickle.loads(pickle.dumps(loaded)).predict(x), 'predict (pickled twice)')
    return loaded


def assert_identical_learners(learner, loaded, x):
    """
    Asserts that a learner that has been restored from a fitted learner uses native objects of the same types and that
    all supported types of predictions, including incremental predictions, are identical.

    :param learner: The original learner
    :param loaded:  The restored learner
    :param x:       The feature matrix that should be used for obtaining predictions
    """
    for attribute, expected_type in (
        ('model_', RuleModel),
        ('output_space_info_', OutputSpaceInfo),
        ('marginal_probability_calibration_model_', MarginalProbabilityCalibrationModel),
        ('joint_probability_calibration_model_', JointProbabilityCalibrationModel),
    ):
        original_value = getattr(learner, attribute, None)

        if original_value is not None:
            loaded_value = getattr(loaded, attribute)
            assert isinstance(loaded_value, expected_type)
            assert type(loaded_value) is type(original_value), f'{attribute}: The type of the native object differs'

    num_compared = 0

    for method_name in ('predict', 'predict_proba', 'decision_function'):
        if _supports(learner, method_name, x):
            _assert_identical(getattr(learner, method_name)(x), getattr(loaded, method_name)(x), method_name)
            num_compared += 1

    for method_name in ('predict_incrementally', 'predict_proba_incrementally', 'decision_function_incrementally'):
        if _supports(learner, method_name, x):
            _assert_identical_incremental_predictions(learner, loaded, method_name, x)

    assert num_compared > 0, 'No predictions have been compared'
